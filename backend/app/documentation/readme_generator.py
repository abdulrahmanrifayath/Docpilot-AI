from typing import Any, Dict, List


class ReadmeGenerator:
    def generate(
        self,
        repo_name: str,
        languages: Dict[str, Any],
        frameworks: List[str],
        stats: Dict[str, Any],
        structure: Dict[str, Any],
        apis: List[Dict[str, Any]],
        models: List[Dict[str, Any]],
    ) -> str:
        """Generates an exhaustive, production-grade README.md."""
        lang_list = [f"`{lang}` ({info.get('percent', 0)}%)" for lang, info in list(languages.items())[:5]]
        fw_badges = " ".join([f"`{fw}`" for fw in frameworks]) or "`Standard Frameworks`"

        api_rows = []
        for ep in apis[:10]:
            auth = "🔒 Yes" if ep.get("auth_required") else "🌐 Public"
            desc = ep.get("docstring") or f"Handler for {ep.get('path')}"
            desc = desc.split("\n")[0].replace("|", "\\|")
            api_rows.append(f"| `{ep.get('method')}` | `{ep.get('path')}` | {auth} | {desc} |")
        api_table = "\n".join(api_rows) if api_rows else "| GET | / | 🌐 Public | Health / Welcome Endpoint |"

        folder_rows = []
        for path, purpose in list(structure.get("folder_purposes", {}).items())[:12]:
            folder_rows.append(f"| `{path}` | {purpose} |")
        folder_table = "\n".join(folder_rows) if folder_rows else "| `src` | Primary application source code |"

        models_list = "\n".join([f"- **`{m['name']}`**: Table `{m.get('table_name', m['name'].lower())}` ({len(m.get('fields', []))} fields)" for m in models[:8]]) or "- Domain models configured"

        return f"""# {repo_name}

> Automatically analyzed and documented by **DocPilot AI**.

## 📌 Overview

**{repo_name}** is a software repository utilizing modern software engineering practices.
This documentation provides comprehensive details on the codebase architecture, modules, REST APIs, database schemas, and onboarding workflows.

---

## 🛠️ Technology Stack

- **Primary Languages**: {', '.join(lang_list) if lang_list else 'Polyglot'}
- **Frameworks & Libraries**: {fw_badges}
- **Total Lines of Code**: `{stats.get('lines', 0):,}` across `{stats.get('files', 0)}` analyzed files
- **Key Symbols**: `{stats.get('classes', 0)}` classes, `{stats.get('functions', 0)}` functions, `{stats.get('apis', 0)}` API endpoints, `{stats.get('models', 0)}` database models

---

## 📂 Project Structure

| Directory | Purpose |
|:---|:---|
{folder_table}

---

## 🚀 Getting Started

### Prerequisites

- Ensure the relevant language runtime is installed:
{chr(10).join([f"  - {l}" for l in list(languages.keys())[:3]])}
- Git installed on your system

### Installation & Run

```bash
# Clone the repository
git clone <repository-url>
cd {repo_name}

# Install dependencies and start the service
# Refer to package managers (pip, npm, cargo, etc.)
```

---

## 🔌 API Endpoints Summary

| Method | Endpoint | Authentication | Description |
|:---|:---|:---|:---|
{api_table}

---

## 🗄️ Database Models

{models_list}

---

## 📖 Additional Documentation

- [System Architecture Guide](./ARCHITECTURE.md)
- [API Documentation Specification](./API_REFERENCE.md)
- [Developer Onboarding Guide](./ONBOARDING.md)
- [Technical Health Report](./TECHNICAL_REPORT.md)

---
*Generated by [DocPilot AI](https://github.com/DocPilot-AI) on repository analysis.*
"""
